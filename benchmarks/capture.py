"""
Capture state declarations from a real model run.

`benchmarks shadow` can measure what an agent's own declarations contribute, but
only if it has a capture: the literal `<contextgc-state>` blocks a model emitted,
keyed by turn. There is no honest way to invent one. A capture is a record of
what a real model said, and a synthetic stand-in would measure the harness rather
than the write path.

So this module only does the mechanical part, and refuses to pretend:

* `capture` runs a real conversation against any OpenAI-compatible endpoint and
  writes what came back, including the declarations.
* `verify` checks an existing capture is well formed and re-derivable.
* Nothing here fabricates a declaration. `shadow` with no capture still refuses.

An endpoint can be anything that speaks the OpenAI chat API -- ``openai`` with a
key, or a local ``ollama serve``. It is configured by environment variable, never
by argument, so a key cannot land in a shell history or a CI log.
"""

import hashlib
import json
import os
import re
from typing import Any, Dict, List, Optional

#: The protocol block, as the agent emits it.
BLOCK = re.compile(r"<contextgc-state>(.*?)</contextgc-state>", re.DOTALL)

CAPTURE_VERSION = 1

#: Bumped whenever the *prompt* changes shape -- not when the file format does.
#: A capture is only resumable against the prompt that produced it: reusing turns
#: captured under a different prompt yields a file that names one model, one
#: endpoint and one set of turns while having been generated by two different
#: prompts, and nothing in it would say so. The first real capture (42 turns) was
#: invalidated this way, when the protocol stopped being taught twice and the
#: stale turns were silently carried forward.
PROMPT_VERSION = 2

#: Asked for the block only, so the reply is a declaration rather than a
#: restatement of the turn.
_ASK = (
    "Emit only the <contextgc-state> block for that turn, "
    "or emit nothing if it changed nothing."
)


def extract_blocks(text: str) -> List[str]:
    """Every state block in one assistant turn, in order."""
    return [m.strip() for m in BLOCK.findall(text or "")]


def parse_block(block: str) -> Optional[Dict[str, Any]]:
    """
    One block as a dict, or None if it does not parse.

    Malformed blocks are counted rather than dropped silently: a model that
    emits broken JSON a third of the time is a finding about the protocol, not
    something to smooth over.
    """
    try:
        parsed = json.loads(block)
    except (ValueError, TypeError):
        return None
    return parsed if isinstance(parsed, dict) else None


def summarise(
    turns: List[Dict[str, Any]],
    schema: Optional[Dict[str, Any]] = None,
) -> Dict[str, Any]:
    """
    What a capture contains, for a human deciding whether to trust it.

    ``declared_turns`` is the number that matters. A capture where the model
    never declared anything measures nothing, and saying so plainly is more
    useful than a passing comparison.

    ``compliance`` is the share of assistant turns that produced a block. It is
    the first thing to look at, because a model that complies on a tenth of
    turns caps the entire write path at a tenth of its theoretical value no
    matter how good the compiler is.

    ``in_schema_ratio`` is the one that decides whether the write path is worth
    having, and it is not the compliance figure. A model can comply on every turn
    and declare a different invented key each time; measured on the first real
    capture, fixing a prompt defect took compliance from 59% to 90% while the
    share of declarations naming a schema key stayed at 37%. Compliance measures
    whether the model spoke; this measures whether it said anything the tracker
    asked for.

    Parsing is delegated to ``parse_declaration`` rather than repeated here. The
    hand-rolled version disagreed with the pipeline it was reporting on: given
    ``{"revoke":"current_file"}`` -- a bare string where the protocol asks for a
    list -- the pipeline records one revocation, while this summary iterated the
    string and reported ten, `_` `r` `e` `n` `i` `c` `u` `t` `f` `l`. A summary
    that overstates what the model said by a factor of ten is worse than none.
    """
    from contextgc.state_protocol import parse_declaration

    total = malformed = 0
    keys: Dict[str, int] = {}
    declared_keys = 0
    in_schema_keys = 0
    known = set()
    if schema:
        raw = schema.get("entities") if isinstance(schema.get("entities"), dict) else schema
        known = {k for k in raw if not k.startswith("_") and k != "__immutable__"}

    for turn in turns:
        for block in extract_blocks(turn.get("content", "")):
            total += 1
            declaration = parse_declaration(f"<contextgc-state>{block}</contextgc-state>")
            if declaration.malformed:
                malformed += 1
                continue
            for group in (
                declaration.asserts, declaration.pins,
                declaration.revokes, declaration.unsure,
            ):
                for key in group:
                    keys[key] = keys.get(key, 0) + 1
            # Revocations are not "the model supplied a fact", so they are
            # excluded here: a model that revokes four keys it never asserted has
            # not demonstrated it can name the schema.
            for group in (declaration.asserts, declaration.pins, declaration.unsure):
                for key in group:
                    declared_keys += 1
                    if not known or key in known:
                        in_schema_keys += 1
    declared_turns = sum(1 for t in turns if extract_blocks(t.get("content", "")))
    return {
        "turns": len(turns),
        "blocks": total,
        "malformed": malformed,
        "declared_turns": declared_turns,
        "compliance": round(declared_turns / len(turns), 3) if turns else 0.0,
        "declared_keys": declared_keys,
        "in_schema_keys": in_schema_keys if known else None,
        "in_schema_ratio": (
            round(in_schema_keys / declared_keys, 3) if declared_keys and known else None
        ),
        "keys": dict(sorted(keys.items(), key=lambda kv: -kv[1])),
    }


def declaration_index(turns: List[Dict[str, Any]]) -> Dict[str, Dict[int, str]]:
    """
    The captured blocks in the shape shadow mode replays.

    The capture file keeps every turn verbatim, because that is the evidence; a
    second, derived index exists so the same file can be replayed without
    re-parsing it. The two shapes were incompatible -- capture wrote
    ``{version, endpoint, turns: [{transcript, role, content}]}`` while shadow
    read ``{transcript_id: {turn: block}}`` -- so a capture could be loaded,
    reported as valid, and then replay *nothing* while the report said every key
    agreed. The read path was agreeing with itself.
    """
    index: Dict[str, Dict[int, str]] = {}
    for turn in turns:
        transcript = turn.get("transcript")
        if not transcript:
            continue
        blocks = extract_blocks(turn.get("content", ""))
        if blocks:
            index.setdefault(transcript, {})[int(turn.get("index", 0))] = blocks[0]
    return index


def verify(
    capture: Dict[str, Any], schema: Optional[Dict[str, Any]] = None
) -> List[str]:
    """Problems with a capture, as a list of strings. Empty means usable.

    Given a schema, a capture whose declarations almost never name a defined key
    is reported as a problem in its own right. It is still replayable -- shadow
    mode can show exactly how far off it was, which is more useful than refusing
    -- but "the model emitted blocks" is not the same as "the model emitted
    something this tracker asked for", and only the second is a result.
    """
    problems: List[str] = []
    if capture.get("version") != CAPTURE_VERSION:
        problems.append(
            f"capture version is {capture.get('version')!r}, expected {CAPTURE_VERSION}"
        )
    if capture.get("legacy_prompt"):
        problems.append(
            "this capture was made with the duplicated-prompt defect "
            "(legacy_prompt=true). It is a valid record of what that harness did "
            "and an invalid measurement of the protocol; re-run without "
            "--legacy-prompt to measure the protocol."
        )
    if not capture.get("endpoint"):
        problems.append("no endpoint recorded, so the capture cannot be attributed")
    turns = capture.get("turns")
    if not isinstance(turns, list) or not turns:
        problems.append("no turns recorded")
        return problems
    for index, turn in enumerate(turns):
        if "role" not in turn or "content" not in turn:
            problems.append(f"turn {index} is missing role or content")
    summary = summarise(turns, schema=schema)
    if summary["blocks"] == 0:
        problems.append(
            "the model never emitted a <contextgc-state> block, so this capture "
            "would measure nothing; check that the agent was taught the protocol"
        )
    if summary["malformed"]:
        problems.append(
            f"{summary['malformed']} of {summary['blocks']} blocks do not parse as JSON"
        )
    if summary["in_schema_ratio"] is not None and summary["in_schema_ratio"] < 0.5:
        problems.append(
            f"only {summary['in_schema_keys']} of {summary['declared_keys']} "
            f"declarations ({summary['in_schema_ratio']:.0%}) name a key the "
            f"schema defines; the rest are keys the read path could never "
            f"corroborate, so this capture shows what the model said rather than "
            f"what the tracker gained"
        )
    return problems


def _client() -> Any:
    """
    An OpenAI-compatible client, from the environment.

    ``CONTEXTGC_CAPTURE_BASE_URL`` points at a local server (ollama, vLLM,
    LM Studio) and ``CONTEXTGC_CAPTURE_MODEL`` names the model. With neither, the
    official client is used and it will look for its own key.
    """
    base = os.environ.get("CONTEXTGC_CAPTURE_BASE_URL")
    model = os.environ.get("CONTEXTGC_CAPTURE_MODEL")
    try:
        from openai import OpenAI
    except ImportError as exc:  # pragma: no cover - dependency guidance
        raise SystemExit(
            "capturing needs the openai client:\n"
            "  pip install openai\n"
            "and either OPENAI_API_KEY, or CONTEXTGC_CAPTURE_BASE_URL pointing at a\n"
            "local OpenAI-compatible server."
        ) from exc
    if base:
        return OpenAI(base_url=base, api_key=os.environ.get("OPENAI_API_KEY", "local")), model
    if not os.environ.get("OPENAI_API_KEY"):
        # The library's own error is a stack trace from inside the client, which
        # is a poor place to discover the one thing standing between you and the
        # project's largest open measurement.
        raise SystemExit(
            "capture needs a reachable model, and none is configured.\n\n"
            "  Option 1 -- any OpenAI key (smallest model is fine; this measures\n"
            "  the protocol, not the model):\n\n"
            "    export OPENAI_API_KEY=sk-...\n"
            "    export CONTEXTGC_CAPTURE_MODEL=gpt-4o-mini\n\n"
            "  Option 2 -- a local model, no key and no cost. Any OpenAI-compatible\n"
            "  server works; ollama is the usual one:\n\n"
            "    ollama serve && ollama pull qwen2.5:7b\n"
            "    export CONTEXTGC_CAPTURE_BASE_URL=http://localhost:11434/v1\n"
            "    export CONTEXTGC_CAPTURE_MODEL=qwen2.5:7b\n\n"
            "  Then, from the repository root:\n\n"
            "    python -m benchmarks capture --transcript benchmarks/corpus/sample.txt \\\n"
            "      --out captures/run1.json --limit 6 --schema coding\n"
            "    python -m benchmarks capture --verify --out captures/run1.json\n"
            "    python -m benchmarks shadow --captures captures/run1.json \\\n"
            "      --corpus swe-agent --schema coding\n\n"
            "Nothing is fabricated when no model is reachable: without a capture,\n"
            "`benchmarks shadow` refuses to run, because a synthetic declaration set\n"
            "would measure this harness rather than the write path."
        )
    return OpenAI(), model or os.environ.get("CONTEXTGC_CAPTURE_MODEL", "gpt-4o-mini")


def _ask(client: Any, model_name: Optional[str], messages: List[Dict[str, str]]) -> str:
    """
    One completion, or a message that says what to do about it.

    The client's own error for an unreachable endpoint is a sixty-line traceback
    from inside httpx, which is a bad place to discover that the local server
    stopped. The missing-key case in `_client` already got this treatment; an
    endpoint that was up and then was not deserves the same.
    """
    try:
        return client.chat.completions.create(
            model=model_name, messages=messages
        ).choices[0].message.content or ""
    except Exception as exc:  # noqa: BLE001 - re-raised as advice below
        if exc.__class__.__name__ in ("APIConnectionError", "ConnectError"):
            where = os.environ.get("CONTEXTGC_CAPTURE_BASE_URL", "the configured endpoint")
            raise SystemExit(
                f"capture could not reach {where}.\n\n"
                f"  If this is a local server, check it is still running:\n"
                f"    curl {where.rstrip('/')}/models\n"
                f"    ollama ps\n\n"
                f"  Completed turns are written to the output file as they arrive,\n"
                f"  so re-running the same command resumes instead of starting over."
            ) from exc
        raise


def _write(payload: Dict[str, Any], out_path: str) -> None:
    """Persist the capture. Called after every turn, not once at the end."""
    parent = os.path.dirname(os.path.abspath(out_path))
    if parent:
        os.makedirs(parent, exist_ok=True)
    payload["declarations"] = declaration_index(payload["turns"])
    with open(out_path, "w", encoding="utf-8") as handle:
        json.dump(payload, handle, indent=2)
        handle.write("\n")


def _fingerprint(
    instruction: str, schema: Any, context_chars: int, legacy_prompt: bool = False
) -> str:
    """
    A short digest of everything that shapes the prompt.

    Resume is only safe when this matches, so a capture cannot be stitched
    together from turns asked under different instructions, schemas or context
    budgets.
    """
    material = json.dumps(
        {
            "prompt_version": PROMPT_VERSION,
            "instruction": instruction,
            "ask": _ASK,
            "schema": schema,
            "context_chars": context_chars,
            "legacy_prompt": legacy_prompt,
        },
        sort_keys=True,
        default=str,
    )
    return hashlib.sha256(material.encode("utf-8")).hexdigest()[:16]


def _resume(out_path: str, fingerprint: str) -> List[Dict[str, Any]]:
    """
    Turns from a previous run of the same capture, so a dropped connection does
    not throw away the model calls that already succeeded.

    Reused only if the version, the transcript and the prompt fingerprint all
    match. Replaying turns captured from a different transcript would attach
    declarations to turns that never produced them, and replaying turns captured
    under a different prompt would mix two experiments into one file -- both are
    failures this module was rewritten to prevent.
    """
    if not os.path.exists(out_path):
        return []
    try:
        with open(out_path, encoding="utf-8") as handle:
            previous = json.load(handle)
    except (ValueError, OSError):
        return []
    if previous.get("version") != CAPTURE_VERSION or not isinstance(
        previous.get("turns"), list
    ):
        return []
    if previous.get("prompt_fingerprint") != fingerprint:
        return []
    return previous["turns"]


def capture(
    transcript_path: str,
    out_path: str,
    limit: int = 20,
    schema_path: Optional[str] = None,
    system: Optional[str] = None,
    context_chars: Optional[int] = None,
    progress: bool = True,
    legacy_prompt: bool = False,
) -> Dict[str, Any]:
    """
    Run real conversations and record what the model actually declared.

    Each turn sends the compiled context plus the protocol instruction, takes the
    model's reply verbatim, and stores it. The declarations are whatever the model
    emitted -- this function never adds, corrects or invents one.
    """
    from benchmarks.corpus import load_synthetic
    from contextgc import compile_messages, load_schema, render_instruction

    client, model_name = _client()
    transcripts = load_synthetic(transcript_path)[:limit]
    schema = load_schema(schema_path) if schema_path else None
    instruction = system or render_instruction()

    # Budget in characters, not turns. Turn counts hide the problem: every
    # transcript here is 14 messages, so a turn window never binds, yet the
    # largest is 32k characters -- roughly 8k tokens, twice a 4k context. The
    # endpoint then truncates the tail of the prompt itself, and the model is
    # asked to declare against a turn it cannot see. The declaration rate would
    # come back low and look like a finding about the protocol.
    if context_chars is None:
        context_chars = int(
            os.environ.get("CONTEXTGC_CAPTURE_CONTEXT_CHARS", "12000")
        )

    # What the prompt costs before any trajectory: the system instruction, the
    # protocol the compiler teaches, and the closing "emit only the block"
    # request. Measured rather than assumed -- budgeting for the trajectory
    # alone overshot the real limit by 592 characters, and the endpoint would
    # have trimmed the oldest turn to compensate without saying so.
    _baseline, _ = compile_messages(
        [
            {"role": "system", "content": instruction},
            {"role": "user", "content": _ASK},
        ],
        schema=schema,
        teach_protocol=True,
    )
    overhead = sum(len(m.get("content") or "") for m in _baseline)

    def fit(messages: List[Dict[str, str]]) -> List[Dict[str, str]]:
        """
        Drop the oldest turns until the prompt fits, keeping every system message.

        This changes what the model sees, so the caller records how often it
        happened. A capture that quietly truncated its way to a better number
        would be the exact failure this project exists to catch.
        """
        systems = [m for m in messages if m["role"] == "system"]
        others = [m for m in messages if m["role"] != "system"]
        budget = context_chars - overhead - sum(
            len(m.get("content") or "") for m in systems
        )
        kept: List[Dict[str, str]] = []
        for message in reversed(others):
            budget -= len(message.get("content") or "")
            if budget < 0 and kept:
                break
            kept.append(message)
        # `kept` was collected back-to-front, so only that tail is reversed.
        # Reversing the whole list put the system message last and the turns in
        # reverse order, which the compiler then merged into one system prompt --
        # so the model was asked to declare against a conversation assembled
        # backwards, and nothing said so.
        return systems + list(reversed(kept))

    fingerprint = _fingerprint(instruction, schema, context_chars, legacy_prompt)
    recorded: List[Dict[str, Any]] = _resume(out_path, fingerprint)
    # Which (transcript, turn) pairs a previous run already paid for. Resuming
    # keeps the capture honest as long as the key is the trajectory position,
    # because that is what a declaration is filed against.
    done = {(t.get("transcript"), t.get("index")) for t in recorded}
    if done and progress:
        print(f"  resuming: {len(done)} turns already captured", flush=True)

    payload: Dict[str, Any] = {
        "version": CAPTURE_VERSION,
        # Recorded, not assumed: a capture that cannot say which model produced it
        # is an anecdote.
        "endpoint": os.environ.get("CONTEXTGC_CAPTURE_BASE_URL", "api.openai.com"),
        "model": model_name,
        "transcript_path": transcript_path,
        "schema": schema_path,
        "legacy_prompt": legacy_prompt,
        "prompt_fingerprint": fingerprint,
        "prompt_version": PROMPT_VERSION,
        "turns": recorded,
    }
    asked = 0
    truncated = 0
    for number, transcript in enumerate(transcripts, 1):
        if progress:
            print(
                f"  [{number}/{len(transcripts)}] {transcript.id} "
                f"({transcript.n_chars} chars)",
                flush=True,
            )
        # Walk the *real* trajectory and ask a model to declare what each
        # assistant turn changed.
        #
        # The previous version held a generic conversation and merely borrowed
        # the transcript's id, so its turn indices had no relationship to the
        # transcript's. Replaying it would have applied declarations to unrelated
        # turns and reported every key as agreeing -- a measurement of nothing,
        # arrived at honestly and printed confidently.
        #
        # Declaring over a real trajectory is the question worth asking: given
        # what an agent actually said, does stating the state outright beat
        # matching it with a pattern?
        # `teach_protocol=True`, not a hand-merged system prompt. The compiler
        # strips protocol markup from every role on the way in -- correctly, so a
        # user turn cannot inject a declaration -- and that includes the system
        # message. A system prompt built by concatenating the instruction by hand
        # arrives at the model with the tag removed and the model never sees a
        # protocol at all.
        #
        # And the instruction is *not* also placed in the system slot here. Doing
        # both sent the protocol twice, 801 bytes per turn, and the duplicated
        # `[STATE_PROTOCOL]` wrapper is what the model then echoed back: a quarter
        # of the non-compliant replies in the first capture were the wrapper tag
        # and the format line restated as prose.
        #
        # `legacy_prompt` restores that defect on purpose, so the before/after in
        # the README is reproducible rather than remembered. It is recorded in
        # the payload and makes `verify` refuse the result, because a capture
        # made with a doubled prompt is not a valid measurement and must not sit
        # in `captures/` looking like one.
        history: List[Dict[str, str]] = (
            [{"role": "system", "content": instruction}] if legacy_prompt else []
        )
        for position, message in enumerate(transcript.messages):
            role = message.get("role")
            if role == "system":
                # Appended, not assigned into a fixed slot. Assigning over one
                # replaced the protocol instruction with the transcript's own
                # system message, so a corpus that carried one would produce a
                # capture with zero declarations and the report would read as
                # "the model never emitted a block" -- blaming the model for a
                # prompt we deleted.
                history.append({"role": "system", "content": message.get("content", "")})
                continue
            if role != "assistant":
                history.append({"role": role, "content": message.get("content", "")})
                continue

            said = message.get("content", "")
            history.append({"role": "assistant", "content": said})
            if (transcript.id, position) in done:
                continue
            window = fit(history)
            if len(window) < len(history):
                truncated += 1
            compiled, _telemetry = compile_messages(
                window, schema=schema, teach_protocol=True
            )
            # Asked for the block only, so the reply is a declaration rather than
            # a restatement of the turn.
            compiled = compiled + [{
                "role": "user",
                "content": _ASK,
            }]
            reply = _ask(client, model_name, compiled)
            asked += 1
            declared = bool(extract_blocks(reply))
            # Every assistant turn is recorded, including the silent ones.
            # Skipping them made the capture look like it had fewer turns than
            # were asked about, and left no way to report the only number that
            # says whether the protocol is usable: in how many turns did the
            # model actually comply?
            recorded.append({
                "transcript": transcript.id,
                # The turn being declared. Shadow mode replays by this index, so
                # it has to be the trajectory's index, not this loop's.
                "index": position,
                "role": "assistant",
                "declared": declared,
                "content": reply,
            })
            done.add((transcript.id, position))
            # Written after every turn. A local server that drops after the
            # fortieth call should cost one call, not the whole run.
            _write(payload, out_path)
            if progress:
                marker = "declared" if declared else "silent"
                print(
                    f"      turn {position:>2}  {marker}  "
                    f"({len(reply)} chars, window {len(window)} msgs)",
                    flush=True,
                )

    payload["prompts_asked"] = asked
    payload["context_chars"] = context_chars
    payload["context_truncated_prompts"] = truncated
    _write(payload, out_path)
    if progress:
        declared = sum(1 for t in recorded if t.get("declared"))
        print(
            f"\n  {len(recorded)} turns captured ({declared} declared, "
            f"{len(recorded) - declared} silent), {truncated} prompts truncated, "
            f"wrote {out_path}",
            flush=True,
        )
    return payload
